using EventReservationApp.Data;
using EventReservationApp.Models.Dtos;
using EventReservationApp.Services.Implementations;
using EventReservationApp.Services.Interfaces;
using EventReservationApp.Tests.TestHelpers;
using Microsoft.EntityFrameworkCore;
using Xunit;

namespace EventReservationApp.Tests;

/// <summary>
/// A retry with the same Idempotency-Key must get the first answer without the
/// operation running again. Runs against SQL Server LocalDB, because it relies on
/// the unique (UserId, Key) index and on transactions, which the in-memory
/// provider ignores. Skip with: dotnet test --filter "Category!=Integration"
/// </summary>
[Trait("Category", "Integration")]
public class IdempotencyServiceTests : IAsyncLifetime
{
    private LocalDbTestDatabase _database = null!;
    private int _eventId;

    public async Task InitializeAsync()
    {
        _database = await LocalDbTestDatabase.CreateAsync();

        await using var db = _database.CreateContext();
        db.AddUser("user-1");
        db.AddUser("user-2");
        var @event = db.AddEvent(0, name: "Event A", capacity: 5); // 0 = id generated by SQL Server
        await db.SaveChangesAsync();
        _eventId = @event.Id;
    }

    public async Task DisposeAsync() => await _database.DisposeAsync();

    // Every call gets its own context, like a separate HTTP request.
    private async Task<IdempotentResult> ReserveAsync(string userId, Guid key, int eventId)
    {
        await using var db = _database.CreateContext();
        var reservations = CreateReservationsService(db, userId);
        return await CreateIdempotencyService(db, userId).ExecuteAsync(
            key, IdempotentOperations.ReservationCreate, eventId,
            () => reservations.ReserveForCurrentUserAsync(eventId, null));
    }

    private async Task<IdempotentResult> CancelAsync(string userId, Guid key, int reservationId)
    {
        await using var db = _database.CreateContext();
        var reservations = CreateReservationsService(db, userId);
        return await CreateIdempotencyService(db, userId).ExecuteAsync(
            key, IdempotentOperations.ReservationCancel, reservationId,
            () => reservations.CancelForCurrentUserAsync(reservationId));
    }

    private static MyReservationsService CreateReservationsService(ApplicationDbContext db, string userId) =>
        new(new ReservationService(db), FakeCurrentUser.For(userId));

    private static IdempotencyService CreateIdempotencyService(ApplicationDbContext db, string userId) =>
        new(db, FakeCurrentUser.For(userId));

    private async Task<int> CountAsync<T>(Func<ApplicationDbContext, IQueryable<T>> query)
    {
        await using var db = _database.CreateContext();
        return await query(db).CountAsync();
    }

    [Fact]
    public async Task RepeatedKey_GetsTheFirstAnswer_WithoutReservingAgain()
    {
        var key = Guid.NewGuid();

        var first = await ReserveAsync("user-1", key, _eventId);
        var retry = await ReserveAsync("user-1", key, _eventId);

        Assert.Equal(IdempotencyOutcome.Executed, first.Outcome);
        Assert.True(first.Result!.Success);
        // Run again, it would answer AlreadyReserved; the retry gets the original success.
        Assert.Equal(IdempotencyOutcome.Replayed, retry.Outcome);
        Assert.True(retry.Result!.Success);
        Assert.Null(retry.Result.ErrorCode);
        Assert.Equal(1, await CountAsync(db => db.EventReservations));
    }

    [Fact]
    public async Task RepeatedCancel_GetsTheOriginalSuccess_InsteadOfNotFound()
    {
        await ReserveAsync("user-1", Guid.NewGuid(), _eventId);
        int reservationId;
        await using (var db = _database.CreateContext())
        {
            reservationId = await db.EventReservations.Select(r => r.Id).SingleAsync();
        }

        var key = Guid.NewGuid();
        var first = await CancelAsync("user-1", key, reservationId);
        var retry = await CancelAsync("user-1", key, reservationId);

        Assert.True(first.Result!.Success);
        Assert.Equal(IdempotencyOutcome.Replayed, retry.Outcome);
        Assert.True(retry.Result!.Success);
    }

    [Fact]
    public async Task KeyReusedForAnotherEvent_IsRejected_AndNothingRuns()
    {
        int otherEventId;
        await using (var db = _database.CreateContext())
        {
            var other = db.AddEvent(0, name: "Event B");
            await db.SaveChangesAsync();
            otherEventId = other.Id;
        }

        var key = Guid.NewGuid();
        await ReserveAsync("user-1", key, _eventId);
        var reused = await ReserveAsync("user-1", key, otherEventId);

        Assert.Equal(IdempotencyOutcome.KeyReusedForDifferentRequest, reused.Outcome);
        Assert.Null(reused.Result);
        Assert.Equal(0, await CountAsync(db => db.EventReservations.Where(r => r.EventId == otherEventId)));
    }

    [Fact]
    public async Task SameKeyFromAnotherUser_IsIndependent()
    {
        // Keys are scoped to the user from the token: one user can neither block
        // nor read another user's stored answer.
        var key = Guid.NewGuid();

        var first = await ReserveAsync("user-1", key, _eventId);
        var other = await ReserveAsync("user-2", key, _eventId);

        Assert.Equal(IdempotencyOutcome.Executed, first.Outcome);
        Assert.Equal(IdempotencyOutcome.Executed, other.Outcome);
        Assert.Equal(2, await CountAsync(db => db.EventReservations));
    }

    [Fact]
    public async Task OperationThatThrows_StoresNothing_SoTheRetryRunsIt()
    {
        var key = Guid.NewGuid();

        await using (var db = _database.CreateContext())
        {
            await Assert.ThrowsAsync<InvalidOperationException>(() =>
                CreateIdempotencyService(db, "user-1").ExecuteAsync(
                    key, IdempotentOperations.ReservationCreate, _eventId,
                    () => throw new InvalidOperationException("Database went away.")));
        }

        Assert.Equal(0, await CountAsync(db => db.IdempotencyRecords));

        var retry = await ReserveAsync("user-1", key, _eventId);

        Assert.Equal(IdempotencyOutcome.Executed, retry.Outcome);
        Assert.True(retry.Result!.Success);
    }

    [Fact]
    public async Task ParallelRequestsWithTheSameKey_ReserveOnce_AndAllGetSuccess()
    {
        // e.g. the original call is still running when the retry arrives: the
        // retry's insert of the key waits for it, then gets its stored answer.
        var key = Guid.NewGuid();

        var results = await Task.WhenAll(
            Enumerable.Range(0, 5).Select(_ => ReserveAsync("user-1", key, _eventId)));

        Assert.Single(results, r => r.Outcome == IdempotencyOutcome.Executed);
        Assert.All(results, r => Assert.True(r.Result!.Success));
        Assert.Equal(1, await CountAsync(db => db.EventReservations));
    }
}
